// Grants the Vampiric Embrace Spell
func (priest *Priest) applyVampiricEmbrace() {
	if !priest.Talents.VampiricEmbrace {
		return
	}

	vampEmbraceTimer := priest.NewTimer()
	spellData.VampiricEmbrace.Each(func(_ int32, rank *spelldata.Spell) { priest.registerVampiricEmbrace(rank, vampEmbraceTimer) })
}

// Your Shadow damage spells have a X% chance to increase the Shadow damage you deal by 2% for 15 sec, stacking up to 5 times.
func (priest *Priest) applyShadowWeaving() {
	if priest.Talents.ShadowWeaving == 0 {
		return
	}

	// The debuff 15258 is A_MOD_SCHOOL_MASK_DAMAGE_FROM_CASTER, so it raises
	// this priest's shadow damage alone; the port builds swAuras by parsing
	// ShadowWeavingTriggered onto each target's aura with spelldata.ParseEffects
	// and FromCaster.
	swAuras := priest.NewEnemyAuraArray(func(target *core.Unit) *core.Aura {
		auraConfig := spelldata.AuraConfig(spellData.ShadowWeavingTriggered.ByID(15258))
		auraConfig.Label += " - " + priest.Label

		return target.GetOrRegisterAura(auraConfig).AttachDDBC(int(auraConfig.GetStacks()), int(auraConfig.MaxStacks), &priest.AttackTables,
			func(_ *core.Simulation, spell *core.Spell, _ *core.AttackTable) float64 {
				if spell.SpellSchool.Matches(core.SpellSchoolShadow) {
					return spellData.ShadowWeavingTriggered.MultiplierAt(priest.Talents.ShadowWeaving)
				}
				return 1
			})
	})

	priest.MakeProcTriggerAura(core.ProcTrigger{
		Name:             "Shadow Weaving Trigger",
		CanProcFromProcs: true, // 15257, 15331-15334 carry the bit.
		ClassSpellMask:   PriestShadowSpells,
		Callback:         core.CallbackOnSpellHitDealt,
		Outcome:          core.OutcomeLanded,
		ProcChance:       spellData.ShadowWeaving.FractionAt(priest.Talents.ShadowWeaving),
		Handler: func(sim *core.Simulation, spell *core.Spell, result *core.SpellResult) {
			swAuras.Get(result.Target).Activate(sim)
			swAuras.Get(result.Target).AddStack(sim)
		},
	})
}

