// Grants the Mind Flay ability
func (priest *Priest) applyMindFlay() {
	if !priest.Talents.MindFlay {
		return
	}
	spellData.MindFlay.Each(func(_ int32, rank *spelldata.Spell) { priest.registerMindFlaySpell(rank) })
}

