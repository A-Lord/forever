// When activated, reduces the Mana cost of your next spell by 100% and increases its critical effect chance by 25% if it is a non-periodic spell and capable of a critical effect.
func (priest *Priest) applyInnerFocus() {
	if !priest.Talents.InnerFocus {
		return
	}

	innerFocusRank := spellData.InnerFocus.Highest()
	priest.InnerFocusAura = priest.RegisterAura(spelldata.AuraConfig(innerFocusRank))
	spelldata.ParseEffects(&priest.Character, priest.InnerFocusAura, innerFocusRank)
	spelldata.AttachChargeSpender(&priest.Character, priest.InnerFocusAura, innerFocusRank, "Inner Focus - Spend")

	config := spelldata.SpellConfig(&priest.Unit, innerFocusRank, spelldata.Flags(core.SpellFlagAPL|core.SpellFlagNoOnCastComplete))
	config.Cast.DefaultCast.NonEmpty = true
	config.RelatedSelfBuff = priest.InnerFocusAura
	config.ApplyEffects = func(sim *core.Simulation, _ *core.Unit, _ *core.Spell) {
		priest.InnerFocusAura.Activate(sim)
		priest.InnerFocusAura.SetStacks(sim, priest.InnerFocusAura.MaxStacks)
	}
	innerFocusSpell := priest.RegisterSpell(config)

	priest.AddMajorCooldown(core.MajorCooldown{
		Spell: innerFocusSpell,
		Type:  core.CooldownTypeMana,
	})
}

// Allows X% of your Mana regeneration to continue while casting.
func (priest *Priest) applyMeditation() {
	if priest.Talents.Meditation == 0 {
		return
	}

	priest.PseudoStats.SpiritRegenRateCasting += spellData.Meditation.FractionAt(priest.Talents.Meditation)
	priest.UpdateManaRegenRates()
}

