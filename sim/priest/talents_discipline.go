// Launches a volley of holy light at the target, causing X Holy damage to an enemy, or Y healing to an ally, instantly and every 1 sec for 2 sec.
func (priest *Priest) applyPenance() {
	if !priest.Talents.Penance {
		return
	}

	penanceTimer := priest.NewTimer()
	spellData.Penance.Each(func(_ int32, rank *spelldata.Spell) {
		priest.registerPenance(rank, penanceTimer)
	})
}

