// Infuses the target with power, increasing their spell damage and healing done by 20% for 15 sec.
func (priest *Priest) applyPowerInfusion() {
	if !priest.Talents.PowerInfusion {
		return
	}

	piAura := buffs.NewSpellDataPowerInfusionsAura(&priest.Unit, true, 0)

	piSpell := priest.RegisterSpell(core.SpellConfig{
		ActionID:    core.ActionID{SpellID: 10060},
		ClassFlags:  spellData.PowerInfusion.Highest().ClassFlags,
		SpellSchool: core.SpellSchoolHoly,
		Flags:       core.SpellFlagHelpful,
		ManaCost: core.ManaCostOptions{
			BaseCostPercent: 20,
		},
		Cast: core.CastConfig{
			CD: core.Cooldown{
				Timer:    priest.NewTimer(),
				Duration: buffs.PowerInfusionsCooldown(),
			},
			DefaultCast: core.Cast{
				NonEmpty: true,
			},
		},
		ApplyEffects: func(sim *core.Simulation, target *core.Unit, _ *core.Spell) {
			piAura.Activate(sim)
		},
	})

	priest.AddMajorCooldown(core.MajorCooldown{
		Spell:    piSpell,
		Priority: core.CooldownPriorityDefault,
		Type:     core.CooldownTypeDPS,
	})
}
