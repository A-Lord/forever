// Increases the damage and healing of your instant cast spells by X%.
func (priest *Priest) applyTwinDisciplines() {
	if priest.Talents.TwinDisciplines == 0 {
		return
	}

	priest.AddStaticMod(core.SpellModConfig{
		Kind:       core.SpellMod_DamageDone_Pct,
		FloatValue: spellData.TwinDisciplines.FractionAt(priest.Talents.TwinDisciplines),
		ClassMask:  PriestSpellInstant,
	})
}

