// The generated half of sim/core/spelldata: every spell the sim can reach, with its effects and
// power costs, and the talent curves a trait talent's ranks are priced from. The hand-written half
// of the package states the contract this file writes to - see the comment on store.go - and the
// init below is what installs the data, since package variables are set before any init runs.
func renderStoreFile(rows []storeSpell, curves map[int32][][]float64, namer *rankEnumNamer) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/database/gen_spelldata. DO NOT EDIT.\n\n")
	b.WriteString("package spelldata\n\n")
	b.WriteString("import (\n\"github.com/wowsims/forever/sim/core\"\n\"github.com/wowsims/forever/sim/core/dbcenums\"\n)\n\n")

	b.WriteString("var generatedSpells = []Spell{\n")
	for _, row := range rows {
		b.WriteString(formatStoreRow(row, namer))
	}
	b.WriteString("}\n\n")

	b.WriteString("var generatedCurves = map[int32][][]float64{\n")
	for _, id := range sortedCurveIDs(curves) {
		var rows []string
		for _, row := range curves[id] {
			values := make([]string, len(row))
			for i, v := range row {
				values[i] = num(v)
			}
			rows = append(rows, "{"+strings.Join(values, ", ")+"}")
		}
		fmt.Fprintf(&b, "\t%d: {%s},\n", id, strings.Join(rows, ", "))
	}
	b.WriteString("}\n\n")

	b.WriteString("func init() { install(generatedSpells, generatedCurves) }\n")

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("the generated store does not parse, refusing to write it: %w", err)
	}
	return out, nil
}

func sortedCurveIDs(curves map[int32][][]float64) []int32 {
	ids := make([]int32, 0, len(curves))
	for id := range curves {
		ids = append(ids, id)
	}
	sort.Slice(ids, func(i, j int) bool { return ids[i] < ids[j] })
	return ids
}

// One row per line, with its effects and powers under it: a field the client leaves at zero is left
// out, so what the row states is what the client states.
func formatStoreRow(s storeSpell, namer *rankEnumNamer) string {
	parts := []string{fmt.Sprintf("ID: %d", s.ID), fmt.Sprintf("Name: %q", s.Name)}
	add := func(format string, args ...any) {
		parts = append(parts, fmt.Sprintf(format, args...))
	}

	if s.Rank != "" {
		add("Rank: %q", s.Rank)
	}
	if s.School != 0 {
		add("School: %d", s.School)
	}
	if s.Speed != 0 {
		add("Speed: %s", num32(s.Speed))
	}
	if words := hexWords(s.Attr[:]); words != "" {
		add("Attr: [17]uint32{%s}", words)
	}
	if s.SpellLevel != 0 {
		add("SpellLevel: %d", s.SpellLevel)
	}
	if s.BaseLevel != 0 {
		add("BaseLevel: %d", s.BaseLevel)
	}
	if s.MaxLevel != 0 {
		add("MaxLevel: %d", s.MaxLevel)
	}
	if s.CastTimeMs != 0 {
		add("CastTimeMs: %d", s.CastTimeMs)
	}
	if s.DurationMs != 0 {
		add("DurationMs: %d", s.DurationMs)
	}
	if s.MinRange != 0 {
		add("MinRange: %s", num32(s.MinRange))
	}
	if s.MaxRange != 0 {
		add("MaxRange: %s", num32(s.MaxRange))
	}
	if s.CooldownMs != 0 {
		add("CooldownMs: %d", s.CooldownMs)
	}
	if s.CategoryCooldownMs != 0 {
		add("CategoryCooldownMs: %d", s.CategoryCooldownMs)
	}
	if s.GCDMs != 0 {
		add("GCDMs: %d", s.GCDMs)
	}
	if s.Category != 0 {
		add("Category: %d", s.Category)
	}
	if s.StartRecoveryCategory != 0 {
		add("StartRecoveryCategory: %d", s.StartRecoveryCategory)
	}
	if s.ChargeCategory != 0 {
		add("ChargeCategory: %d", s.ChargeCategory)
	}
	if s.DefenseType != 0 {
		add("DefenseType: %d", s.DefenseType)
	}
	if s.DispelType != 0 {
		add("DispelType: %d", s.DispelType)
	}
	if s.Mechanic != 0 {
		add("Mechanic: %d", s.Mechanic)
	}
	if s.PreventionType != 0 {
		add("PreventionType: %d", s.PreventionType)
	}
	if s.MaxStack != 0 {
		add("MaxStack: %d", s.MaxStack)
	}
	if s.ProcChance != 0 {
		add("ProcChance: %d", s.ProcChance)
	}
	if s.ProcCharges != 0 {
		add("ProcCharges: %d", s.ProcCharges)
	}
	if words := hexWords(s.ProcFlags[:]); words != "" {
		add("ProcFlags: [2]uint32{%s}", words)
	}
	if s.ICDMs != 0 {
		add("ICDMs: %d", s.ICDMs)
	}
	if s.RPPM != 0 {
		add("RPPM: %s", num32(s.RPPM))
	}
	if s.FlatThreat != 0 {
		add("FlatThreat: %s", num32(s.FlatThreat))
	}
	if !s.ClassFlags.isZero() {
		add("ClassFlags: %s", formatClassFlags(s.ClassFlags))
	}
	if words := hexWords(s.AuraInterrupt[:]); words != "" {
		add("AuraInterrupt: [2]uint32{%s}", words)
	}
	if words := hexWords(s.ChannelInterrupt[:]); words != "" {
		add("ChannelInterrupt: [2]uint32{%s}", words)
	}
	if s.StanceMask != 0 {
		add("StanceMask: %#x", s.StanceMask)
	}
	if s.MaxTargets != 0 {
		add("MaxTargets: %d", s.MaxTargets)
	}
	if s.EquipClass != 0 {
		add("EquipClass: %d", s.EquipClass)
	}
	if s.EquipSubclass != 0 {
		add("EquipSubclass: %d", s.EquipSubclass)
	}
	if s.EquipInvType != 0 {
		add("EquipInvType: %d", s.EquipInvType)
	}
	if len(s.Labels) > 0 {
		labels := make([]string, len(s.Labels))
		for i, label := range s.Labels {
			labels[i] = strconv.Itoa(int(label))
		}
		add("Labels: []int16{%s}", strings.Join(labels, ", "))
	}
	if len(s.RefIDs) > 0 {
		refs := make([]string, len(s.RefIDs))
		for i, ref := range s.RefIDs {
			refs[i] = strconv.Itoa(int(ref))
		}
		add("RefIDs: []int32{%s}", strings.Join(refs, ", "))
	}
	if s.ProcChanceSource != procChanceColumn {
		add("ProcChanceSource: %s", s.ProcChanceSource)
	}
	if s.ProcChanceEffect != 0 {
		add("ProcChanceEffect: %d", s.ProcChanceEffect)
	}
	if s.ProcHint != 0 {
		add("ProcHint: %s", formatProcHint(s.ProcHint))
	}

	var b strings.Builder
	fmt.Fprintf(&b, "{%s", strings.Join(parts, ", "))
	if len(s.Effects) > 0 {
		b.WriteString(",\nEffects: []Effect{\n")
		for _, e := range s.Effects {
			b.WriteString(formatStoreEffect(e, namer))
		}
		b.WriteString("}")
	}
	if len(s.Powers) > 0 {
		powers := make([]string, len(s.Powers))
		for i, p := range s.Powers {
			powers[i] = formatStorePower(p)
		}
		fmt.Fprintf(&b, ",\nPowers: []Power{%s}", strings.Join(powers, ", "))
	}
	b.WriteString("},")
	for _, note := range s.overrideNotes {
		fmt.Fprintf(&b, " // %s", note)
	}
	b.WriteString("\n")
	return b.String()
}

func formatStoreEffect(e storeEffect, namer *rankEnumNamer) string {
	parts := []string{
		fmt.Sprintf("ID: %d", e.ID),
		fmt.Sprintf("SpellID: %d", e.SpellID),
		fmt.Sprintf("Index: %d", e.Index),
	}
	add := func(format string, args ...any) {
		parts = append(parts, fmt.Sprintf(format, args...))
	}

	if e.Type != 0 {
		add("Type: %s", namer.storeEffect(e.Type))
	}
	if e.Aura != 0 {
		add("Aura: %s", namer.storeAura(e.Aura))
	}
	if e.BasePoints != 0 {
		add("BasePoints: %s", num(e.BasePoints))
	}
	if e.PPL != 0 {
		add("PPL: %s", num(e.PPL))
	}
	if e.SpellLevel != 0 {
		add("SpellLevel: %d", e.SpellLevel)
	}
	if e.MaxLevel != 0 {
		add("MaxLevel: %d", e.MaxLevel)
	}
	if e.Variance != 0 {
		add("Variance: %s", num(e.Variance))
	}
	if e.SPCoef != 0 {
		add("SPCoef: %s", num(e.SPCoef))
	}
	if e.APCoef != 0 {
		add("APCoef: %s", num(e.APCoef))
	}
	if e.PvpMult != 0 {
		add("PvpMult: %s", num32(e.PvpMult))
	}
	if e.Amplitude != 0 {
		add("Amplitude: %s", num32(e.Amplitude))
	}
	if e.PeriodMs != 0 {
		add("PeriodMs: %d", e.PeriodMs)
	}
	if e.RadiusMin != 0 {
		add("RadiusMin: %s", num32(e.RadiusMin))
	}
	if e.RadiusMax != 0 {
		add("RadiusMax: %s", num32(e.RadiusMax))
	}
	if e.Misc != 0 {
		add("Misc: %d", e.Misc)
	}
	if e.Misc2 != 0 {
		add("Misc2: %d", e.Misc2)
	}
	if !e.ClassFlags.isZero() {
		add("ClassFlags: %s", formatClassFlags(e.ClassFlags))
	}
	if e.TriggerID != 0 {
		add("TriggerID: %d", e.TriggerID)
	}
	if e.ChainTargets != 0 {
		add("ChainTargets: %d", e.ChainTargets)
	}
	if e.ChainAmp != 0 {
		add("ChainAmp: %s", num32(e.ChainAmp))
	}
	if e.Mechanic != 0 {
		add("Mechanic: %d", e.Mechanic)
	}
	if e.PointsPerResource != 0 {
		add("PointsPerResource: %s", num32(e.PointsPerResource))
	}
	if e.Target != [2]uint8{} {
		add("Target: [2]uint8{%d, %d}", e.Target[0], e.Target[1])
	}
	if e.Attributes != 0 {
		add("Attributes: %d", e.Attributes)
	}

	row := "{" + strings.Join(parts, ", ") + "},"
	if e.HandLinked {
		row += " // the client states no trigger here, handTriggers does"
	}
	return row + "\n"
}

func formatStorePower(p storePower) string {
	parts := []string{fmt.Sprintf("Type: %d", p.Type)}
	if p.Cost != 0 {
		parts = append(parts, fmt.Sprintf("Cost: %d", p.Cost))
	}
	if p.CostPerLevel != 0 {
		parts = append(parts, fmt.Sprintf("CostPerLevel: %d", p.CostPerLevel))
	}
	if p.CostPct != 0 {
		parts = append(parts, fmt.Sprintf("CostPct: %s", num32(p.CostPct)))
	}
	if p.PerSecond != 0 {
		parts = append(parts, fmt.Sprintf("PerSecond: %d", p.PerSecond))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

// The family is the namespace the mask words are read in, so a mask alone is never emitted without
// one; the client states the mask in decimal, which is how the sim's talent code names it.
func formatClassFlags(f storeClassFlags) string {
	var words []string
	for i, word := range f.Mask {
		if word != 0 {
			words = append(words, fmt.Sprintf("%d: %d", i, word))
		}
	}
	if len(words) == 0 {
		return fmt.Sprintf("core.ClassFlags{Family: %d}", f.Family)
	}
	return fmt.Sprintf("core.ClassFlags{Family: %d, Mask: [4]uint32{%s}}", f.Family, strings.Join(words, ", "))
}

// A bit field is written as the words that carry bits, by index: most of the 17 attribute words are
// empty on any one spell, and hex is how the client's flag names read.
func hexWords(words []uint32) string {
	var set []string
	for i, word := range words {
		if word != 0 {
			set = append(set, fmt.Sprintf("%d: %#x", i, word))
		}
	}
	return strings.Join(set, ", ")
}

// A float32 column is printed at float32 precision: the DB widens it, and the shortest float32 form
// converts back to the same bits without carrying the widening's digits into the file.
func num32(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 32)
}

// The store's data, ready to write: the rows and the curves. Everything is rendered before anything
// is written, the way the class files are.
func loadStoreInputs(db *sql.DB, ladderIDs []int32, trees map[int]int) (*storeInputs, error) {
	tables, err := loadSpellTables(db)
	if err != nil {
		return nil, err
	}

	roots, gearRoots, err := storeRoots(db, tables, ladderIDs)
	if err != nil {
		return nil, err
	}

	// The store's extra ids are captured as rows but not as roots: the rendering re-reads them from
	// extra_ids.go, so what is captured has to be everything that rendering will reach - or an extra
	// id would render as a row with a name and nothing else, whether or not the store was
	// regenerated - while the roots stay what the client alone says they are.
	withExtras, err := withExtraIDs(tables, roots)
	if err != nil {
		return nil, err
	}

	// The spells a rank reads a number off by name are roots of their own: nothing inside the closure
	// points at them, so they are asked for once everything else has been reached.
	siblings, err := siblingSpells(db, reachableSpells(tables, withExtras))
	if err != nil {
		return nil, err
	}
	roots = namedIDs(tables, roots, siblings)

	rendered, err := withExtraIDs(tables, roots)
	if err != nil {
		return nil, err
	}
	ids := reachableSpells(tables, rendered)

	nodes, points, err := traitPoints(db, trees)
	if err != nil {
		return nil, err
	}

	in := captureStoreInputs(tables, roots, ids, nodes, points)
	in.ItemRoots = gearRoots
	return in, nil
}

// The store's data, from the client rows it is built from rather than from the database: the same
// path the regeneration check runs, so what it checks is what the generator writes.
func renderStore(in *storeInputs, namer *rankEnumNamer) ([]byte, error) {
	tables := in.tables()

	roots, err := withExtraIDs(tables, in.Roots)
	if err != nil {
		return nil, err
	}
	ids := reachableSpells(tables, roots)

	linkHandTriggers(tables, ids)

	curves := storeCurves(tables, in.TraitNodes, in.TraitPoints, ids)

	effects := 0
	for _, id := range ids {
		effects += len(tables.effects[id])
	}
	fmt.Fprintf(progress, "spelldata: %d roots, %d reachable spells, %d effects\n", len(roots), len(ids), effects)

	rows := make([]storeSpell, len(ids))
	for i, id := range ids {
		rows[i] = tables.row(id)
		applyTooltipHints(tables, &rows[i])
	}
	if err := applyOverrides(rows, overrides.Spells); err != nil {
		return nil, err
	}

	return renderStoreFile(rows, curves, namer)
}

// The trigger edges the client's server-side handlers make and the data does not state, written
// onto the driver's effect so that Drivers() reaches the triggered spell the way it does for a
// stated edge.
func linkHandTriggers(t *spellTables, ids []int32) {
	inStore := map[int32]bool{}
	for _, id := range ids {
		inStore[id] = true
	}

	for driver, triggered := range handTriggers {
		if !inStore[driver] {
			continue
		}
		for _, id := range triggered {
			if !inStore[id] {
				continue
			}
			linkHandTrigger(t, driver, id)
		}
	}
}

func linkHandTrigger(t *spellTables, driver int32, triggered int32) {
	effects := t.effects[driver]
	for _, e := range effects {
		if e.TriggerID == triggered {
			return
		}
	}
	for i := range effects {
		if effects[i].TriggerID == 0 {
			effects[i].TriggerID = triggered
			effects[i].HandLinked = true
			return
		}
	}

	// Every effect of the driver already fires something, so the link has nowhere to go and
	// Drivers() would not reach the triggered spell. Named rather than dropped, since the entry was
	// written by hand for exactly that reach.
	fmt.Fprintf(progress,
		"spelldata: spell %d has no effect free to carry the hand link to %d, so nothing drives it\n",
		driver, triggered)
}

// A trait talent is one spell whose per-rank numbers sit on the tree's curves. The store indexes
// them by the position EffectN counts by rather than by the client's EffectIndex, which has gaps,
// and a position the tree prices no curve for repeats the spell's own base value: Ladder.Talent
// wants one value per rank on every position up to the last one the tree prices.
//
// Every node of every class tree is read, not only the ones the class files turned into ladders: a
// talent the class file could not name is still a spell the sim can register by id.
//
// A node of one rank has no ladder to state, and its single priced value goes onto the effect's base
// points instead: that is the number the class table states for it, and writing it into the row
// rather than into a curve is what makes Find(id) and Talent(id, 1).Rank(1) agree about it.
func storeCurves(t *spellTables, nodes []traitNode, points map[int32]map[int32]map[int32]float64,
	ids []int32) map[int32][][]float64 {
	inStore := map[int32]bool{}
	for _, id := range ids {
		inStore[id] = true
	}

	curves := map[int32][][]float64{}
	pricedBy := map[int32]int32{}

	// What each priced spell was priced at, whether that went into a curve or onto the row's base
	// points, so that a second definition stating the same numbers is not reported as a disagreement.
	pricedRows := map[int32][][]float64{}
	for _, node := range nodes {
		if !inStore[node.SpellID] {
			continue
		}

		// The class generator takes the tree's numbers only where the tree states more ranks than the
		// skill line's own ladder does, so a one-rank node whose spell a skill line teaches is
		// described by its own rows and not by the tree: Ice Block, Last Stand and Relentless Strikes
		// are priced by a node and state the client's base all the same. A node no skill line teaches
		// - a talent Forever added, like Thousand Cuts - has nothing else describing it.
		if node.MaxRanks == 1 && node.TaughtBySkillLine {
			continue
		}

		priced := map[int32]map[int32]float64{}
		for index, curve := range points[node.DefinitionID] {
			if values, ok := curveRanks(curve, node.MaxRanks); ok {
				priced[index] = values
			}
		}

		rows := curveRows(t.effects[node.SpellID], priced, node.MaxRanks)
		if len(rows) == 0 {
			continue
		}

		// The client keeps retired talent nodes around, and a retired twin prices the same
		// spell as the node the game uses: hunter Lightning Reflexes 19168 is 3/6/9/12/15 on
		// definition 134447 and 2/4/6/8/10 on 142605. The lowest definition id within the
		// first tree by id is the one kept, which is what the class tables generate from, and a
		// disagreement is named on stderr rather than resolved silently.
		if seen, ok := pricedBy[node.SpellID]; ok {
			if !sameCurves(pricedRows[node.SpellID], rows) {
				fmt.Fprintf(progress,
					"spelldata: talent definitions %d and %d price spell %d differently, keeping %d\n",
					seen, node.DefinitionID, node.SpellID, seen)
			}
			continue
		}
		pricedBy[node.SpellID] = node.DefinitionID
		pricedRows[node.SpellID] = rows

		if node.MaxRanks == 1 {
			bakeRank(t.effects[node.SpellID], rows)
			continue
		}
		curves[node.SpellID] = rows
	}
	return curves
}

// The one rank's values onto the effects they belong to, by the position curveRows counted in.
func bakeRank(effects []storeEffect, rows [][]float64) {
	for position, row := range rows {
		effects[position].BasePoints = row[0]
	}
}

// Every class tree's nodes in the order the curves are read in - tree by tree, lowest id first, so
// that the first definition to price a spell is the same one whether the points come from the
// database or from the committed inputs - and the points each definition states.
func traitPoints(db *sql.DB, trees map[int]int) ([]traitNode, map[int32]map[int32]map[int32]float64, error) {
	var all []traitNode
	points := map[int32]map[int32]map[int32]float64{}

	for _, treeID := range sortedTreeIDs(trees) {
		nodes, err := traitNodes(db, treeID)
		if err != nil {
			return nil, nil, err
		}
		for _, node := range nodes {
			all = append(all, node)
			if _, ok := points[node.DefinitionID]; ok {
				continue
			}
			curve, err := traitCurves(db, node.DefinitionID)
			if err != nil {
				return nil, nil, err
			}
			points[node.DefinitionID] = curve
		}
	}
	return all, points, nil
}

// One talent node: the definition its curves hang off, the spell it grants and the rank cap the game
// enforces. A one-rank node states no ladder, and its single value is baked into the spell's base
// points by storeCurves rather than kept as a curve of one.
type traitNode struct {
	DefinitionID int32
	SpellID      int32
	MaxRanks     int32

	// Whether a skill line teaches the spell, which is what says the tree is not the only thing
	// describing it - see storeCurves.
	TaughtBySkillLine bool
}

func traitNodes(db *sql.DB, treeID int) ([]traitNode, error) {
	var nodes []traitNode
	err := eachRow(db, fmt.Sprintf(`
		SELECT DISTINCT d.ID, COALESCE(d.SpellID, 0), e.MaxRanks,
		       EXISTS (SELECT 1 FROM SkillLineAbility sla WHERE sla.Spell = d.SpellID)
		FROM TraitNode tn
		JOIN TraitNodeXTraitNodeEntry x ON x.TraitNodeID = tn.ID
		JOIN TraitNodeEntry e ON e.ID = x.TraitNodeEntryID
		JOIN TraitDefinition d ON d.ID = e.TraitDefinitionID
		WHERE tn.TraitTreeID = %d AND d.SpellID > 0 AND e.MaxRanks > 0
		ORDER BY d.ID, e.MaxRanks`, treeID), func(rows *sql.Rows) error {
		var n traitNode
		if err := rows.Scan(&n.DefinitionID, &n.SpellID, &n.MaxRanks, &n.TaughtBySkillLine); err != nil {
			return err
		}
		nodes = append(nodes, n)
		return nil
	})
	return nodes, err
}

// The rank values by effect position, from the curves the tree prices by the client's EffectIndex.
func curveRows(effects []storeEffect, priced map[int32]map[int32]float64, maxRanks int32) [][]float64 {
	last := -1
	for position, e := range effects {
		if priced[int32(e.Index)] != nil {
			last = position
		}
	}
	if last < 0 {
		return nil
	}

	rows := make([][]float64, last+1)
	for position := 0; position <= last; position++ {
		e := effects[position]
		row := make([]float64, maxRanks)
		for rank := int32(1); rank <= maxRanks; rank++ {
			value, ok := priced[int32(e.Index)][rank]
			if !ok {
				value = e.BasePoints
			}
			row[rank-1] = value
		}
		rows[position] = row
	}
	return rows
}

func sameCurves(a, b [][]float64) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if len(a[i]) != len(b[i]) {
			return false
		}
		for j := range a[i] {
			if a[i][j] != b[i][j] {
				return false
			}
		}
	}
	return true
}

func sortedTreeIDs(trees map[int]int) []int {
	ids := make([]int, 0, len(trees))
	for _, tree := range trees {
		ids = append(ids, tree)
	}
	sort.Ints(ids)
	return ids
}
