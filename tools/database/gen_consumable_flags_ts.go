package database

import (
	"fmt"
	"os"
	"strings"

	"github.com/wowsims/forever/sim/core/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
)

const consumableFlagsTSPath = "ui/sim/proto/consumable_flags_auto_gen.ts"

// A ConsumesSpec field the spec no longer has, and the item a set flag selected. ItemID is 0 where
// the client ships no such item, or the field held no item.
type RemovedConsumesField struct {
	Name   protoreflect.Name
	Number protoreflect.FieldNumber
	ItemID int32
	Pet    bool
}

// The flags and the drums enum ConsumesSpec carried before api version 17. A set flag becomes its
// item in extra_ids, or pet_extra_ids for the pet's.
var RemovedConsumesFields = []RemovedConsumesField{
	{"superSapper", 8, 0, false}, // Super Sapper Charge 23827
	{"goblinSapper", 9, 10646, false},
	{"drums_id", 12, 0, false},
	{"scroll_agi", 13, 10309, false}, // Scroll of Agility IV
	{"scroll_str", 14, 10310, false}, // Scroll of Strength IV
	{"scroll_int", 15, 10308, false}, // Scroll of Intellect IV
	{"scroll_spi", 16, 10306, false}, // Scroll of Spirit IV
	{"scroll_arm", 17, 10305, false}, // Scroll of Protection IV
	{"pet_scroll_agi", 18, 10309, true},
	{"pet_scroll_str", 19, 10310, true},
	{"nightmare_seed", 20, 0, false}, // Nightmare Seed 22797
	{"bloodthistle", 24, 0, false},   // Bloodthistle 22710
	{"bogling_root", 25, 5206, false},
}

func protoJSONName(name protoreflect.Name) string {
	var out strings.Builder
	upper := false
	for _, r := range string(name) {
		switch {
		case r == '_':
			upper = true
		case upper:
			out.WriteString(strings.ToUpper(string(r)))
			upper = false
		default:
			out.WriteRune(r)
		}
	}
	return out.String()
}

// Writes RemovedConsumesFields for the UI's migration of saved settings and links. Every entry must
// be reserved in ConsumesSpec by both name and number.
func GenerateConsumableFlagsTSFile() error {
	descriptor := (&proto.ConsumesSpec{}).ProtoReflect().Descriptor()

	var out strings.Builder
	out.WriteString("// Code generated by tools/database/gen_consumable_flags_ts.go. DO NOT EDIT.\n\n")
	out.WriteString("// The ConsumesSpec fields removed in api version 17: the name, JSON name and number each had,\n")
	out.WriteString("// and the item a set flag selected, 0 where there is none.\n")
	out.WriteString("export interface RemovedConsumesField {\n\tname: string;\n\tjsonName: string;\n\tno: number;\n\titemId: number;\n\tpet: boolean;\n}\n\n")
	out.WriteString("export const REMOVED_CONSUMES_FIELDS: ReadonlyArray<RemovedConsumesField> = [\n")
	for _, field := range RemovedConsumesFields {
		if !descriptor.ReservedNames().Has(field.Name) || !descriptor.ReservedRanges().Has(field.Number) {
			return fmt.Errorf("ConsumesSpec does not reserve %s = %d", field.Name, field.Number)
		}
		fmt.Fprintf(&out, "\t{ name: '%s', jsonName: '%s', no: %d, itemId: %d, pet: %t },\n",
			field.Name, protoJSONName(field.Name), field.Number, field.ItemID, field.Pet)
	}
	out.WriteString("];\n")

	if err := os.WriteFile(consumableFlagsTSPath, []byte(out.String()), 0644); err != nil {
		return fmt.Errorf("failed to write %s: %w", consumableFlagsTSPath, err)
	}
	return nil
}
