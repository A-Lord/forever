package database

import (
	"fmt"
	"os"
	"strings"

	"github.com/wowsims/forever/sim/core"
	"github.com/wowsims/forever/sim/core/proto"
)

const consumableFlagsTSPath = "ui/sim/proto/consumable_flags_auto_gen.ts"

// Writes core.ConsumableFlags for the UI, by the TypeScript name of each ConsumesSpec field, so a
// request's database carries the item behind every flag it sets.
func GenerateConsumableFlagsTSFile() error {
	fields := (&proto.ConsumesSpec{}).ProtoReflect().Descriptor().Fields()

	var out strings.Builder
	out.WriteString("// Code generated by tools/database/gen_consumable_flags_ts.go. DO NOT EDIT.\n\n")
	out.WriteString("import type { ConsumesSpec } from '@generated/proto/common';\n\n")
	out.WriteString("// The item each ConsumesSpec flag selects, the pet's flags included.\n")
	out.WriteString("export const CONSUMABLE_FLAG_ITEM_IDS: ReadonlyArray<readonly [keyof ConsumesSpec, number]> = [\n")
	for _, flag := range core.ConsumableFlags {
		field := fields.ByName(flag.Field)
		if field == nil {
			return fmt.Errorf("ConsumesSpec has no field %s", flag.Field)
		}
		fmt.Fprintf(&out, "\t['%s', %d],\n", field.JSONName(), flag.ItemID)
	}
	out.WriteString("];\n")

	if err := os.WriteFile(consumableFlagsTSPath, []byte(out.String()), 0644); err != nil {
		return fmt.Errorf("failed to write %s: %w", consumableFlagsTSPath, err)
	}
	return nil
}
