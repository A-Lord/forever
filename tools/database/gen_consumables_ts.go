const consumablesTSFile = "ui/features/settings/model/consumables_auto_gen.ts"

type tsConsumable struct {
	Const  string
	ID     int32
	Type   string
	Fields []string
}

type tsConsumableList struct {
	Const   string
	Entries []string
}

type tsConsumables struct {
	Imports     string
	Consumables []tsConsumable
	Lists       []tsConsumableList
}

const consumablesTSTemplate = `// Code generated by tools/database/gen_consumables_ts.go. DO NOT EDIT.

{{ .Imports }}

export interface GeneratedConsumable {
	readonly id: number;
	readonly type: ConsumableType;
	readonly actionId: ActionId;
	readonly classAllowlist?: ReadonlyArray<Class>;
	readonly requiredProfession?: Profession;
	readonly allowableRace?: bigint;
	readonly weaponSubclassMask?: number;
	readonly weaponInventoryTypeMask?: number;
}
{{ range .Consumables }}
export const {{ .Const }}: GeneratedConsumable = {
	id: {{ .ID }},
	type: ConsumableType.{{ .Type }},
	actionId: ActionId.fromItemId({{ .ID }}),
{{- range .Fields }}
	{{ . }},
{{- end }}
};
{{ end }}
{{- range .Lists }}
export const {{ .Const }}: ReadonlyArray<GeneratedConsumable> = [
{{- range .Entries }}
	{{ . }},
{{- end }}
];
{{ end }}`

var tsNameSeparators = regexp.MustCompile(`[^A-Za-z0-9]+`)

// The item's name in PascalCase: apostrophes dropped, every other run of punctuation or space a word
// break, and a leading digit prefixed with "Item".
func consumableTSName(name string) string {
	var out strings.Builder
	for _, word := range tsNameSeparators.Split(strings.ReplaceAll(name, "'", ""), -1) {
		if word == "" {
			continue
		}
		runes := []rune(word)
		runes[0] = unicode.ToUpper(runes[0])
		out.WriteString(string(runes))
	}
	if out.Len() == 0 || unicode.IsDigit(rune(out.String()[0])) {
		return "Item" + out.String()
	}
	return out.String()
}

// "ConsumableTypeBattleElixir" -> "BATTLE_ELIXIR_CONSUMABLES".
func consumableTypeListName(consumableType proto.ConsumableType) string {
	name := strings.TrimPrefix(consumableType.String(), "ConsumableType")
	var out strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			out.WriteByte('_')
		}
		out.WriteRune(unicode.ToUpper(r))
	}
	return out.String() + "_CONSUMABLES"
}

// Writes one named export per consumable db.json ships, carrying the fields the settings UI filters
// on, and one list per consumable type. Names shared by several items all take their item id.
func GenerateConsumablesTSFile(db *WowDatabase) error {
	ids := slices.Sorted(maps.Keys(db.Consumables))

	nameCount := map[string]int{}
	for _, id := range ids {
		nameCount[consumableTSName(db.Consumables[id].Name)]++
	}

	file := tsConsumables{}
	usesClass, usesProfession := false, false
	byType := map[proto.ConsumableType][]string{}
	for _, id := range ids {
		consumable := db.Consumables[id]
		entry := tsConsumable{Const: consumableTSName(consumable.Name), ID: id, Type: consumable.Type.String()}
		if nameCount[entry.Const] > 1 {
			entry.Const = fmt.Sprintf("%s%d", entry.Const, id)
		}
		if len(consumable.ClassAllowlist) > 0 {
			usesClass = true
			classes := make([]string, len(consumable.ClassAllowlist))
			for i, class := range consumable.ClassAllowlist {
				classes[i] = "Class." + class.String()
			}
			entry.Fields = append(entry.Fields, "classAllowlist: ["+strings.Join(classes, ", ")+"]")
		}
		if consumable.RequiredProfession != proto.Profession_ProfessionUnknown {
			usesProfession = true
			entry.Fields = append(entry.Fields, "requiredProfession: Profession."+consumable.RequiredProfession.String())
		}
		if consumable.AllowableRace != 0 {
			entry.Fields = append(entry.Fields, fmt.Sprintf("allowableRace: %dn", consumable.AllowableRace))
		}
		if consumable.WeaponSubclassMask != 0 {
			entry.Fields = append(entry.Fields, fmt.Sprintf("weaponSubclassMask: %d", consumable.WeaponSubclassMask))
		}
		if consumable.WeaponInventoryTypeMask != 0 {
			entry.Fields = append(entry.Fields, fmt.Sprintf("weaponInventoryTypeMask: %d", consumable.WeaponInventoryTypeMask))
		}
		file.Consumables = append(file.Consumables, entry)
		byType[consumable.Type] = append(byType[consumable.Type], entry.Const)
	}

	for _, consumableType := range slices.Sorted(maps.Keys(proto.ConsumableType_name)) {
		t := proto.ConsumableType(consumableType)
		file.Lists = append(file.Lists, tsConsumableList{Const: consumableTypeListName(t), Entries: byType[t]})
	}

	commonImports := []string{"ConsumableType"}
	if usesClass {
		commonImports = append([]string{"Class"}, commonImports...)
	}
	if usesProfession {
		commonImports = append(commonImports, "Profession")
	}
	file.Imports = fmt.Sprintf("import { %s } from '@generated/proto/common';\nimport { ActionId } from '@sim/proto/action_id';", strings.Join(commonImports, ", "))

	tmpl, err := template.New("consumables_ts").Parse(consumablesTSTemplate)
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, file); err != nil {
		return err
	}
	return os.WriteFile(consumablesTSFile, buf.Bytes(), 0644)
}
