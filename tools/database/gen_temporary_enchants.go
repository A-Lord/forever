package database

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

const temporaryEnchantConsumablesFile = "sim/common/forever/consumables_imbues_auto_gen.go"

// Registers every temporary enchant consumable db.json ships by its item id. The ids are written out
// rather than read from the loaded database, which the browser's sim does not have when the effects
// register.
func GenerateTemporaryEnchantConsumables(db *WowDatabase) {
	var ids []int32
	for id, consumable := range db.Consumables {
		if consumable.TemporaryEnchant != nil {
			ids = append(ids, id)
		}
	}
	slices.Sort(ids)

	var out strings.Builder
	out.WriteString("// Code generated by tools/database/gen_temporary_enchants.go. DO NOT EDIT.\n\npackage forever\n\n")
	if len(ids) > 0 {
		out.WriteString("import \"github.com/wowsims/forever/sim/common/shared\"\n\n")
	}
	out.WriteString("func RegisterAllTemporaryEnchantConsumables() {\n")
	for _, id := range ids {
		fmt.Fprintf(&out, "\tshared.NewTemporaryEnchantConsumable(%d) // %s\n", id, db.Consumables[id].Name)
	}
	out.WriteString("}\n")

	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(fmt.Sprintf("formatting %s: %v", temporaryEnchantConsumablesFile, err))
	}
	if err := os.WriteFile(temporaryEnchantConsumablesFile, formatted, 0644); err != nil {
		panic(fmt.Sprintf("writing %s: %v", temporaryEnchantConsumablesFile, err))
	}
}
